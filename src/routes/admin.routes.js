import { Router } from 'express';
import { getMembers, deleteMember, updateMemberTier, createMember, viewMemberDetails, viewAllMembers } from '../controllers/admin/members.controller.js';
import { getClassActivities, getAllClassTypes, createClassType, updateClassType, deleteClassType } from '../controllers/admin/classActivities.controller.js';
import { requireAuth } from '../middleware/requireAuth.js';
import { requireAdmin } from '../middleware/requireAdmin.js';
import { createClassSession, deleteSession, editSession } from '../controllers/admin/classSession.controller.js';
import { viewAdminInsights } from '../controllers/admin/insights.controller.js';
import { searchMembersController, viewKiosk } from '../controllers/admin/searchMember.controller.js';
import { createCheckin } from '../controllers/admin/attendance.controller.js';
import { requireGym } from '../middleware/gym.middleware.js';
import { hydrateMember } from '../middleware/hydrateMember.js';
import * as billing from '../controllers/admin/billing.controller.js';
import { billingCsrf } from '../middleware/billingCsrf.js';

const router = Router();
router.use('/admin', requireGym, requireAuth, requireAdmin, hydrateMember);

router.get('/class-activities', getClassActivities);
router.get('/all-members', viewAllMembers);
router.get('/member-details/:id', viewMemberDetails);
router.get('/api/class-types', requireGym, requireAuth, requireAdmin, getAllClassTypes);
router.post('/api/class-types', requireGym, requireAuth, requireAdmin, createClassType);
router.put('/api/class-types/:id', requireGym, requireAuth, requireAdmin, updateClassType);
router.delete('/api/class-types/:id', requireGym, requireAuth, requireAdmin, deleteClassType);
router.post('/api/class-sessions', requireGym, requireAuth, requireAdmin, billingCsrf, createClassSession);
router.delete('/api/class-sessions/:id', requireGym, requireAuth, requireAdmin, billingCsrf, deleteSession);
router.put('/api/class-sessions/:id', requireGym, requireAuth, requireAdmin, billingCsrf, editSession);
router.get('/api/members', getMembers);
router.post('/api/members', createMember);
router.delete('/api/members/:id', deleteMember);
router.patch('/api/members/:id/tier', updateMemberTier);
router.get('/insights', viewAdminInsights);
router.get('/search-members', searchMembersController);
router.post('/checkin', createCheckin);
router.get('/admin-kiosk', viewKiosk);

// Billing endpoints: authenticated admin and tenant isolation are enforced at the /admin app mount.
router.get('/billing', billing.billingPage);
router.get('/billing/overview', billing.getOverview);
router.get('/billing/plans', billing.getPlans);
router.post('/billing/plans', billingCsrf, billing.addPlan);
router.patch('/billing/plans/:id', billingCsrf, billing.editPlan);
router.get('/billing/members', billing.getMembers);
router.get('/billing/memberships', billing.getMemberships);
router.post('/billing/memberships', billingCsrf, billing.addMembership);
router.patch('/billing/memberships/:id', billingCsrf, billing.changeMembership);
router.get('/billing/invoices', billing.getInvoices);
router.get('/billing/invoices/:id', billing.adminInvoice);
router.post('/billing/invoices', billingCsrf, billing.addInvoice);
router.get('/billing/payments', billing.getPayments);
router.post('/billing/payments/:reference/verify', billingCsrf, billing.verifyPayment);
router.post('/billing/payments/manual', billingCsrf, billing.addManualPayment);
router.post('/billing/run', billingCsrf, billing.runRecurringBilling);
router.get('/billing/requests', billing.getPlanRequests);
router.post('/billing/requests/:id', billingCsrf, billing.decidePlanRequest);
router.get('/billing/reminders', billing.getReminders);
router.get('/billing/settings', billing.getPaystackAccount);
router.post('/billing/settings', billingCsrf, billing.savePaystackAccount);
router.get('/billing/export.csv', billing.downloadBillingCsv);
export default router;
